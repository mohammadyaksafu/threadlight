"""Collect the latest eval JSON files into one dated report (markdown + JSON) and check the gates.

    python -m evals.run_all            # summarise what is in evals/reports/
    python -m evals.run_all --strict   # exit 1 if a gate fails (CI)

Gates (plan section 10): field accuracy >= 0.90 on digital and >= 0.80 on scans, type accuracy >= 0.95,
recall@5 >= 0.9 for the production retrieval configuration, zero uncited sentences in stored drafts.
Only numbers that were measured are written; missing evaluations are listed as "not run".
"""

import argparse
import datetime
import json
import sys

from evals.common import REPORTS

GATES = {"digital_field_accuracy": 0.90, "scan_field_accuracy": 0.80, "type_accuracy": 0.95, "recall_at_5": 0.90}


def latest(kind: str) -> dict | None:
    files = sorted(REPORTS.glob("*-%s.json" % kind))
    return json.loads(files[-1].read_text(encoding="utf-8")) if files else None


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--strict", action="store_true")
    ap.add_argument("--primary", default="gemini-flash-lite-3.5", help="model key whose numbers are gated")
    args = ap.parse_args(argv)
    ex, rag, draft = latest("extraction"), latest("rag"), latest("draft")
    today = datetime.date.today().isoformat()
    md = ["# Evaluation report %s" % today, "",
          "Synthetic labelled data generated by `synth/generate.py`. **These are synthetic-set results, not real-world accuracy.**", ""]
    gates, summary = {}, {"date": today, "extraction": {}, "rag": None, "draft": None}

    md += ["## Field extraction", ""]
    if ex:
        md += ["%d documents; %d skipped (%s). Review threshold %.2f." % (ex["documents"], len(ex["skipped"]),
               "no OCR on the machine that ran it" if ex["skipped"] else "none", ex["threshold"]), "",
               "| Model | Group | Docs | Type acc. | Field acc. | All 4 fields right | Auto-accepted | Silent errors |", "|---|---|---|---|---|---|---|---|"]
        for key, s in ex["summary"].items():
            for g, v in s["groups"].items():
                md.append("| %s (`%s`) | %s | %s | %s | %s | %s | %s | %s |" % (key, s["model"], g, v["docs"], v["type_accuracy"], v["field_accuracy"],
                          v["doc_all_fields_correct"], v["auto_accept_rate"], v["silent_error_rate"]))
            summary["extraction"][key] = {**s["groups"].get("all", {}), "model": s["model"], "injection": "%d/%d" % (s["injection_resisted"], s["injection_docs"]),
                                          "pii_leaks": s["pii_leaks"], "p95_latency_ms": s["p95_latency_ms"]}
        md += ["", "Injection documents resisted / PII strings that reached the model input / p95 latency:", ""]
        md += ["- %s: %d/%d, %d, %s ms" % (k, s["injection_resisted"], s["injection_docs"], s["pii_leaks"], s["p95_latency_ms"]) for k, s in ex["summary"].items()]
        p = ex["summary"].get(args.primary)
        if p:
            g = p["groups"]
            if "en/digital" in g:
                gates["digital_field_accuracy"] = g["en/digital"]["field_accuracy"]
            if "en/scan" in g:
                gates["scan_field_accuracy"] = g["en/scan"]["field_accuracy"]
            gates["type_accuracy"] = g["all"]["type_accuracy"]
    else:
        md.append("Not run.")

    md += ["", "## Retrieval (clause to evidence)", ""]
    if rag:
        md += ["%d documents, %d chunks, embeddings `%s`, reranker %s." % (rag["documents"], rag["chunks"], rag["embed_model"],
               "on" if rag["reranker"] else "not installed on the machine that ran it"), "",
               "| Configuration | Clauses | recall@5 | hit@1 | MRR |", "|---|---|---|---|---|"]
        md += ["| %s | %s | %s | %s | %s |" % (k, v["queries"], v["recall_at_5"], v["hit_at_1"], v["mrr"]) for k, v in rag["results"].items()]
        prod = rag["results"].get("hybrid+rewrite+rerank") or rag["results"].get("hybrid+rewrite")
        gates["recall_at_5"] = prod["recall_at_5"] if prod else None
        summary["rag"] = {k: {x: v[x] for x in ("recall_at_5", "hit_at_1", "mrr")} for k, v in rag["results"].items()}
    else:
        md.append("Not run.")

    md += ["", "## Bilingual drafts", ""]
    if draft:
        s = draft["summary"]
        md += ["%d drafts. Mean citation coverage before the checker: %s. Drafts with numbers not in the rule output: %d. "
               "Judge (`%s`) mean faithfulness: %s. Human spot check: see `spot_check` in the JSON." % (
                   s["runs"], s["mean_citation_coverage"], s["runs_with_unsupported_numbers"], s["judge_model"], s["mean_judge_faithfulness"])]
        summary["draft"] = s
    else:
        md.append("Not run.")

    md += ["", "## Gates", "", "| Gate | Threshold | Measured | Result |", "|---|---|---|---|"]
    passed = True
    for k, thr in GATES.items():
        v = gates.get(k)
        ok = v is not None and v >= thr
        passed &= ok or v is None
        md.append("| %s | %s | %s | %s |" % (k, thr, "not measured" if v is None else v, "pass" if ok else ("not run" if v is None else "FAIL")))
    summary["gates"] = gates
    summary["gates_passed"] = passed
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / ("%s.md" % today)).write_text("\n".join(md) + "\n", encoding="utf-8")
    (REPORTS / ("%s.json" % today)).write_text(json.dumps(summary, indent=1, ensure_ascii=False), encoding="utf-8")
    print("\n".join(md))
    if args.strict and not passed:
        sys.exit(1)


if __name__ == "__main__":
    main()
